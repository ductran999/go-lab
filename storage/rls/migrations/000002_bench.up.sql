-- Benchmark dataset: 100k rows across 10 tenants (10k each).
-- Separate table so base labs keep their 3-row dataset.

CREATE TABLE IF NOT EXISTS lab.docs_big (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tenant_id INT NOT NULL,
    body TEXT NOT NULL
);

GRANT SELECT, INSERT, UPDATE, DELETE ON lab.docs_big TO lab_user;

ALTER TABLE lab.docs_big ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation ON lab.docs_big;
CREATE POLICY tenant_isolation ON lab.docs_big
    FOR ALL TO lab_user
    USING (tenant_id = lab.current_tenant())
    WITH CHECK (tenant_id = lab.current_tenant());

INSERT INTO lab.docs_big (tenant_id, body)
SELECT (g % 10) + 1, 'body-' || g FROM generate_series(1, 100000) g;
